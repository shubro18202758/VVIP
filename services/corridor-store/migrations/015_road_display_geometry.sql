-- 015_road_display_geometry.sql
-- Road-true DISPLAY geometry for corridor.road_segments (WP-17, contract C-K).
--
-- The seed draws the road network SCHEMATICALLY (hand-placed polylines
-- between named junctions).  Everything that routes, costs, calibrates or
-- attributes keeps that ``geom``: pgRouting and corridor.road_graph, the
-- diversion planner, the twin, ANPR read attribution (nearest segment within
-- 300 m), camera sites and signal-ingress.  Anything that only DRAWS or
-- ANIMATES the network may follow the real road instead:
-- COALESCE(display_geom, geom).
--
-- SCHEMA ONLY, additive, idempotent, no seed reference: safe on fresh
-- installs (before the seed) and on the ledgered live install.  The rows
-- are filled by services/corridor-store/seed/display_geometry_osm.sql
-- (generated by scripts/gen_display_geometry.py from OpenStreetMap,
-- (c) OpenStreetMap contributors, ODbL 1.0), applied after the seed and
-- post_seed_derivations.sql — only when this column exists.
--
--   1. display_geom geometry(LineString, 4326) — NULL means the segment is
--      drawn schematically (no validated road match).
--   2. display_geom_source — how the line was traced: 'osm_way_stitch' (a
--      name-matched path through the OSM way graph) or 'osrm_route' (an
--      OSRM route over OSM data, the fallback).
--   3. display_geom_meta — provenance: OSM way ids, osm_base timestamp,
--      validation metrics (length ratio, Hausdorff distance, name overlap).
--   4. road_segments_display_geom_ends — a display line starts at the
--      schematic start point and ends at the schematic end point (within
--      1 m): same endpoints, same orientation, so endpoint-chaining
--      consumers (the emulator's patrol paths, the brain's GPS emulation)
--      join segments exactly as they do over geom.  Guarded DROP + re-ADD.
--   5. idx_road_segments_display_geom — GIST, for the bbox reads of the
--      spatial endpoints (they match either geometry).
--
-- Ethics rails (C6): road geometry only — no person, plate or camera column.
--
-- Grammar constraint (007 header): consumed by naive ';'-splitters - no
-- ';' inside string literals, no dollar-quoted bodies, no block comments.

-- =============================================================================
-- 1-3. DISPLAY COLUMNS
-- =============================================================================

ALTER TABLE corridor.road_segments
    ADD COLUMN IF NOT EXISTS display_geom geometry(LineString, 4326);

ALTER TABLE corridor.road_segments
    ADD COLUMN IF NOT EXISTS display_geom_source TEXT
        CHECK (display_geom_source IN ('osm_way_stitch', 'osrm_route'));

ALTER TABLE corridor.road_segments
    ADD COLUMN IF NOT EXISTS display_geom_meta JSONB;

-- =============================================================================
-- 4. SAME ENDPOINTS, SAME ORIENTATION AS geom
-- =============================================================================

ALTER TABLE corridor.road_segments
    DROP CONSTRAINT IF EXISTS road_segments_display_geom_ends;

ALTER TABLE corridor.road_segments
    ADD CONSTRAINT road_segments_display_geom_ends CHECK (
        display_geom IS NULL
        OR (
            ST_DWithin(ST_StartPoint(display_geom)::geography,
                       ST_StartPoint(geom)::geography, 1.0)
            AND ST_DWithin(ST_EndPoint(display_geom)::geography,
                           ST_EndPoint(geom)::geography, 1.0)
        )
    );

-- =============================================================================
-- 5. BBOX READS
-- =============================================================================

CREATE INDEX IF NOT EXISTS idx_road_segments_display_geom
    ON corridor.road_segments USING GIST (display_geom);

COMMENT ON COLUMN corridor.road_segments.display_geom IS
    'DISPLAY ONLY — routing, costs, twin, ANPR attribution, diversions and ingress use geom';

COMMENT ON COLUMN corridor.road_segments.display_geom_source IS
    'how display_geom was traced: osm_way_stitch | osrm_route (NULL with display_geom)';

COMMENT ON COLUMN corridor.road_segments.display_geom_meta IS
    'display_geom provenance: OSM way ids, osm_base timestamp, validation metrics (ODbL 1.0)';
