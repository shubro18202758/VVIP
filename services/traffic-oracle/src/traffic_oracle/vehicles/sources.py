"""AnprSource port — the seam every ANPR camera-read feed plugs into.

THE PORT
--------
An :class:`AnprSource` is anything that can yield a stream of
:class:`AnprRead` records — one camera read of one vehicle plate.  The
persistence layer (this package's router + enforcement rules) consumes
reads through this port ONLY; it never talks to a vendor SDK, a camera, or
a file format directly.

PRODUCTION PATH (documented, NOT shipped)
-----------------------------------------
A real deployment mounts one ``LiveAnprSource``:

    real ANPR/VMS vendor feed (RTSP/HTTP push or poll)
        -> vendor adapter normalizing to the IDENTICAL AnprRead frame schema
        -> source='live_anpr' on every row
        -> identical downstream: sightings, deterministic rules, human approval

The frame schema (``AnprRead``) is frozen by contract C2; a live adapter
must populate the same fields with the same semantics.  Until a real feed
is connected, nothing in this codebase produces ``source='live_anpr'``
reads — the ingest seam only stores the label a vendor adapter sends.

WHAT SHIPS TODAY
----------------
The HTTP ingest seam ``POST /api/v1/vehicles/sightings``
(``vehicles/sighting_processor.py``, contract C-E) is the production
caller: a feed adapter posts one AnprRead per camera read; the oracle
normalizes the plate, refuses future-stamped reads, computes the
watchlist hit from ACTIVE earmarks (never from a label the feed sends),
persists through :func:`traffic_oracle.vehicles.sighting_processor.
persist_read` and runs the e-challan rules — PENDING rows only.  The
event emulator posts ``source='emulated_anpr'``; a real vendor adapter
would post ``source='anpr'`` (stored as ``live_anpr``), which the seam
accepts only on a deployment that enables a registered live feed
(``VVIP_ACCEPT_LIVE_ANPR=1``) — a caller cannot label emulated reads live.

:class:`EmulatedAnprSource` remains the in-process implementation of the
port: fully emulated, clearly labelled (``source='emulated_anpr'`` on
every read, ``label='emulated_anpr'`` on the source), and deterministic —
it replays the ``anpr_read`` frames of a cause tape generated by the event
emulator (uuid5 identity over use_case+seed+camera+plate), optionally
loading the tape straight from the emulator's run ledger
(``emulator.emulation_runs``, migration 009).  The UI badges every
emulated datum; nothing pretends to be a live feed.

ETHICS (C6): vehicles only.  An AnprRead carries a plate and kinematics —
never a face, a person name, or any person-directed field.
"""

from __future__ import annotations

import json
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, AsyncIterator, Iterable, Protocol, runtime_checkable

import structlog

logger = structlog.get_logger(__name__)

__all__ = [
    "AnprRead",
    "AnprSource",
    "EmulatedAnprSource",
    "SOURCE_EMULATED",
    "SOURCE_LIVE",
    "VEHICLE_CLASSES",
    "anpr_read_id",
]

#: The only source labels the schema accepts (migration 010 CHECK).
SOURCE_EMULATED = "emulated_anpr"
SOURCE_LIVE = "live_anpr"  # a real vendor feed (ingest wire label "anpr")

#: The emulator's read-id namespace (event_emulator/tape.py).  Read ids
#: are the EMULATOR's to mint: every tape frame carries its ``read_id``
#: explicitly and the ingest seam uses it verbatim (sighting_processor.py),
#: so this module never has to re-derive one for a real run.
_EMULATOR_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "vvip-event-emulator")

_VEHICLE_CLASSES = frozenset(
    {"car", "two_wheeler", "auto_rickshaw", "bus", "truck", "emergency"}
)

#: The vehicle classes the schema accepts (migration 010 CHECK).
VEHICLE_CLASSES = _VEHICLE_CLASSES


def anpr_read_id(use_case_id: str, seed: int, camera_id: str, plate: str) -> str:
    """The RUN-LESS read id: uuid5 over 'use_case|seed|camera|plate' (C2).

    This is NOT the id a ledgered emulator run produces.  A run recorded
    in emulator.emulation_runs appends '|run:N' to the name (run-scoped
    ids — a replay of the same use case and seed never collides with an
    earlier run's sightings), and every tape frame carries its
    ``read_id`` explicitly, which the ingest seam uses verbatim.  This
    fallback therefore matches only unledgered tapes (``--no-ledger``
    CLI runs and fixtures) — never re-derive a ledgered run's ids here.
    """
    return str(
        uuid.uuid5(_EMULATOR_NAMESPACE, f"{use_case_id}|{seed}|{camera_id}|{plate}")
    )


@dataclass(frozen=True)
class AnprRead:
    """One camera read of one plate — the frozen frame schema (contract C2).

    Fields mirror the emulator tape's ``anpr_read`` payload exactly; the
    tape's ``t_sec`` offset is resolved to an absolute ``t`` by the tape's
    t0 anchor.
    """

    read_id: str
    plate: str
    camera_id: str
    t: datetime
    lon: float
    lat: float
    source: str
    speed_kmh: float | None = None
    heading: float | None = None
    vehicle_class: str | None = "car"  # None: the camera did not classify
    run_id: int | None = None
    matched_plate_hit: str | None = None
    t_sec: float | None = None  # provenance: offset inside the tape

    def __post_init__(self) -> None:
        if self.source != SOURCE_EMULATED and self.source != SOURCE_LIVE:
            raise ValueError(
                f"AnprRead.source must be {SOURCE_EMULATED!r} or "
                f"{SOURCE_LIVE!r} (migration 010 CHECK) — got {self.source!r}"
            )
        if self.vehicle_class is not None and self.vehicle_class not in _VEHICLE_CLASSES:
            raise ValueError(
                f"unknown vehicle_class {self.vehicle_class!r} — "
                f"known: {sorted(_VEHICLE_CLASSES)}"
            )


@runtime_checkable
class AnprSource(Protocol):
    """The port.  ``label`` is surfaced in every API response that derives
    from this source, so emulated data can never lose its badge."""

    @property
    def label(self) -> str: ...

    def reads(self) -> AsyncIterator[AnprRead]: ...


def read_from_tape_payload(
    payload: dict[str, Any],
    *,
    t0: datetime,
    use_case_id: str,
    seed: int,
) -> AnprRead:
    """Normalize one emulator tape ``anpr_read`` payload into an AnprRead.

    Pure; raises on a malformed frame (fail closed rather than inventing
    fields).  ``t`` is derived as t0 + t_sec in UTC — the tape stores only
    the offset so replays re-anchor cleanly.
    """
    t_sec = float(payload["t_sec"])
    t = datetime.fromtimestamp(t0.timestamp() + t_sec, tz=timezone.utc)
    lon, lat = payload["position"]
    return AnprRead(
        read_id=str(
            payload.get("read_id")
            or anpr_read_id(
                use_case_id, seed, str(payload["camera_id"]), str(payload["plate"])
            )
        ),
        plate=str(payload["plate"]),
        camera_id=str(payload["camera_id"]),
        t=t,
        lon=float(lon),
        lat=float(lat),
        source=SOURCE_EMULATED,
        speed_kmh=(
            float(payload["speed_kmh"])
            if payload.get("speed_kmh") is not None
            else None
        ),
        heading=(
            float(payload["heading"])
            if payload.get("heading") is not None
            else None
        ),
        vehicle_class=str(payload.get("vehicle_class", "car")),
        run_id=int(payload["run_id"]) if payload.get("run_id") is not None else None,
        matched_plate_hit=(
            str(payload["matched_plate_hit"])
            if payload.get("matched_plate_hit")
            else None
        ),
        t_sec=t_sec,
    )


class EmulatedAnprSource:
    """The only shipped AnprSource: deterministic, emulated, labelled.

    Construction modes:
        * :meth:`from_tape_frames` — wrap the ``anpr_read`` frames of an
          in-memory cause tape (tests, direct pipeline wiring).
        * :meth:`from_ledger` — load a run's tape from the emulator run
          ledger (``emulator.emulation_runs``) over the oracle's pool; the
          latest run when ``run_id`` is None.

    Both produce the IDENTICAL read stream for the same run: reads are
    ordered by (t_sec, camera_id, plate) — a pure ordering, no clock.
    """

    def __init__(
        self,
        frames: Iterable[dict[str, Any]],
        *,
        t0: datetime,
        use_case_id: str,
        seed: int,
        run_id: int | None = None,
    ) -> None:
        self._t0 = t0
        self._use_case_id = use_case_id
        self._seed = seed
        self._run_id = run_id
        self._frames = sorted(
            (dict(f) for f in frames if f.get("kind") == "anpr_read"),
            key=lambda f: (
                float(f.get("t_sec", 0.0)),  # envelope field (contract C2)
                str(f["payload"]["camera_id"]),
                str(f["payload"]["plate"]),
            ),
        )

    @property
    def label(self) -> str:
        return SOURCE_EMULATED

    @property
    def n_reads(self) -> int:
        return len(self._frames)

    @classmethod
    def from_tape_frames(
        cls,
        frames: Iterable[dict[str, Any]],
        *,
        t0: datetime,
        use_case_id: str,
        seed: int,
        run_id: int | None = None,
    ) -> EmulatedAnprSource:
        """Wrap parsed tape frames: [{frame, t_sec, kind, payload}, ...]."""
        return cls(frames, t0=t0, use_case_id=use_case_id, seed=seed, run_id=run_id)

    @classmethod
    async def from_ledger(
        cls,
        pool: Any,  # asyncpg.Pool
        *,
        run_id: int | None = None,
    ) -> EmulatedAnprSource:
        """Load a run's tape from ``emulator.emulation_runs`` (parameter-bound).

        Latest run when ``run_id`` is None.  Raises ``LookupError`` when no
        run (or no anpr_read frames) exist — callers degrade honestly.
        """
        if run_id is None:
            row = await pool.fetchrow(
                "SELECT run_id, seed, t0_anchor, tape FROM emulator.emulation_runs "
                "ORDER BY run_id DESC LIMIT 1"
            )
        else:
            row = await pool.fetchrow(
                "SELECT run_id, seed, t0_anchor, tape FROM emulator.emulation_runs "
                "WHERE run_id = $1",
                int(run_id),
            )
        if row is None:
            raise LookupError(
                "no emulation run found"
                + (f" with run_id={run_id}" if run_id is not None else "")
            )
        tape_raw = row["tape"]
        tape = json.loads(tape_raw) if isinstance(tape_raw, str) else tape_raw
        t0 = row["t0_anchor"]
        if t0.tzinfo is None:
            t0 = t0.replace(tzinfo=timezone.utc)
        frames = tape.get("frames", [])
        if not any(f.get("kind") == "anpr_read" for f in frames):
            raise LookupError(
                f"emulation run {row['run_id']} carries no anpr_read frames"
            )
        return cls(
            frames,
            t0=t0,
            use_case_id=str(tape.get("use_case_id", "unknown")),
            seed=int(tape.get("seed", row["seed"])),
            run_id=int(row["run_id"]),
        )

    async def reads(self) -> AsyncIterator[AnprRead]:
        for f in self._frames:
            payload = dict(f["payload"])
            # t_sec lives on the frame ENVELOPE (contract C2), never in the
            # payload — merge it in so normalization has one shape to read
            payload.setdefault("t_sec", float(f.get("t_sec", 0.0)))
            if self._run_id is not None:
                payload.setdefault("run_id", self._run_id)
            yield read_from_tape_payload(
                payload,
                t0=self._t0,
                use_case_id=self._use_case_id,
                seed=self._seed,
            )
